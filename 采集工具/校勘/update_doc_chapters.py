import io

P = r"F:\新建文件夹\read - 副本\文档\阅读站说明.md"
s = io.open(P, encoding="utf-8").read()

BLOCK = """### 章节划分

优先按**原文自带的章标记**切，只有标记不完整时才退化为按字数切。

判据（`build_db.py` 的 `split_chapters`）：

| 条件 | 处理 |
|---|---|
| `CHAPTER_RE` 命中 ≥ 3 处，且平均章长 ≤ 30000 字，且最长一段无标记区间 ≤ `max(12×中位间隔, 60000)` | **按原文分章**，`is_real_title=1`，标题用原文 |
| 平均章长 > 30000 字 | 标记只覆盖局部（常见于连载合集），按字数切 |
| 最长无标记区间超阈值 | 标记断裂（只有前几章有标题），按字数切 |
| 命中 < 3 处 | 按字数切，标题 `第N节`，`is_real_title=0` |

细节：

- `CHAPTER_RE = ^[ \\t]*(第[0-9零一二三四五六七八九十百千两]+[章节回卷]|序章|楔子|序言|前言|后记|尾声|终章|番外)[^\\r\\n]{0,40}\\r?$`
  —— **行尾必须写 `\\r?$`**，否则 CRLF 文件里全部失配（这个坑在项目里踩过四次）。
- 第一个章标记之前的内容（简介、卷首语）作为 `开篇` 单独成节，**不丢弃**。
- 标题与正文粘在同一行时（`第61章升魂丹翌日清晨，阳光透过…`），`split_title()` 把标题截到第一个标点或 24 字，剩下的**还给正文**，一个字都不少。
- 单章超过 12000 字时再按 6000 字细分，标题打 `原名·续N`，避免出现几万字一节。

`采集工具\\书库\\rebuild_chapters.py` 只重建 `chapters` 表，**不动 works / characters / AI 简介与角色 bio**；跑完自动重灌 FTS。
`章节划分报告.csv` 记录每部书的模式、章标记数、原/新节数、降级原因，入库后可直接核对。

当前状态：`486 部 / 3,584 节`，其中 **1,780 节使用原文真标题**（82 部作品按原文分章），其余 404 部原文没有完整章标记，仍按字数切。

"""

anchor = "\n## API\n"
assert anchor in s
s = s.replace(anchor, "\n" + BLOCK + "\n## API\n", 1)
io.open(P, "w", encoding="utf-8", newline="\n").write(s)
print("ok", len(s))
